let seq = 0;
function entry(date: string, description: string, lines: LedgerLine[], source: LedgerEntry["source"] = "demo"): LedgerEntry {
  seq += 1;
  return { id: `demo-${String(seq).padStart(3, "0")}`, date, description, source, lines };
}

