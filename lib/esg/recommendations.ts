// ════════════════════════════════════════════════════════════════════════
// lib/esg/recommendations.ts — рекомендации по данным компании.
// Каждая рекомендация опирается на конкретную цифру отчёта; эффект
// посчитан на данных компании как сценарий («если сократить на 10%…»),
// а не взят из внешних обещаний.
// ════════════════════════════════════════════════════════════════════════

import type { Statements } from "@/lib/ledger/engine";
import type { EsgResult } from "./compute";
import type { EsgInput } from "./input";
import { num, pct, som, t } from "./text";

export type Priority = "Высокий" | "Средний" | "Низкий";

export interface Recommendation {
  pillar: "E" | "S" | "G";
  priority: Priority;
  title: string;
  why: string;
  actions: string[];
  effect: string;
  kpi: string;
  horizon: string;
  gri: string;
}

const ORDER: Record<Priority, number> = { "Высокий": 0, "Средний": 1, "Низкий": 2 };

export function recommendations(r: EsgResult, input: EsgInput, s: Statements, periodYear: number): Recommendation[] {
  const out: Recommendation[] = [];
  const e = r.emissions;
  const yearFactor = 12 / r.months; // to annualise period figures in the wording

  // ── E ──
  if (e.electricity > 0 && e.scope12 > 0 && e.electricity / e.scope12 >= 0.3) {
    const kwh = Math.max(0, input.electricityKwh - input.renewableKwh);
    out.push({
      pillar: "E", priority: e.electricity / e.scope12 >= 0.5 ? "Высокий" : "Средний",
      title: "Программа энергоэффективности",
      why: `Электроэнергия даёт ${pct((e.electricity / e.scope12) * 100)} выбросов Охватов 1+2 (${t(e.electricity)}). Энергосистема КР испытывает зимний дефицит, тарифы для юридических лиц пересматриваются.`,
      actions: [
        "Провести энергоаудит или хотя бы поузловой учёт: какие помещения и оборудование потребляют больше всего",
        "Перевести освещение на светодиоды, установить датчики движения в местах общего пользования",
        "Для двигателей, насосов и вентиляции — частотные преобразователи; отключать оборудование вне смен",
        "Закрепить ответственного за ежемесячное снятие показаний и разбор отклонений",
      ],
      effect: `Сокращение потребления на 10% — это ${num(kwh * 0.1, 0)} кВт·ч и ${t(e.electricity * 0.1)} за период${r.energy.cost > 0 ? `, экономия до ${som(r.energy.cost * 0.1)} (10% расходов на энергию и коммунальные услуги)` : ""}.`,
      kpi: "кВт·ч на 1 млн сом выручки; доля помещений с учётом по счётчикам",
      horizon: "до 12 месяцев", gri: "302-4, 305-5",
    });
  }
  if (e.mobile > 0 && e.scope12 > 0 && e.mobile / e.scope12 >= 0.25) {
    out.push({
      pillar: "E", priority: "Средний",
      title: "Снижение расхода топлива автопарком",
      why: `Автопарк даёт ${pct((e.mobile / e.scope12) * 100)} выбросов Охватов 1+2 (${t(e.mobile)}).`,
      actions: [
        "Вести путевые листы и учёт расхода по каждой машине; выявлять отклонения от нормы",
        "Оптимизировать маршруты доставки и загрузку машин",
        "Обучить водителей экономичному вождению, контролировать давление в шинах",
        "При обновлении парка рассматривать газовые, гибридные и электрические машины",
      ],
      effect: `Снижение расхода на 7% — минус ${t(e.mobile * 0.07)} за период.`,
      kpi: "литров на 100 км; т CO₂ на 1 млн сом выручки",
      horizon: "6–18 месяцев", gri: "305-5",
    });
  }
  const coalRow = e.rows.find((x) => x.key === "coal");
  if (coalRow) {
    out.push({
      pillar: "E", priority: "Высокий",
      title: "Отказ от угольного отопления",
      why: `Сжигание угля даёт ${t(coalRow.t)} — ${pct((coalRow.t / Math.max(e.scope12, 1e-9)) * 100)} выбросов Охватов 1+2. Уголь также главный источник загрязнения воздуха зимой.`,
      actions: [
        "Утеплить здания (окна, кровля, стены) — это снижает потребность в тепле при любом источнике",
        "Оценить подключение к газу или к централизованному теплу",
        "Рассмотреть тепловые насосы для небольших помещений",
      ],
      effect: `Полный переход с угля на газ при той же потребности в тепле снизит выбросы этого источника примерно на 40% — около ${t(coalRow.t * 0.4)} за период (по коэффициентам IPCC: газ 56,1 т/ТДж против 94,6 т/ТДж у угля).`,
      kpi: "т угля за отопительный сезон; т CO₂ Охвата 1",
      horizon: "1–3 года", gri: "305-5",
    });
  }
  if (e.scope12 > 0 && !(input.emissionTargetPct > 0)) {
    const annual = e.scope12 * yearFactor;
    out.push({
      pillar: "E", priority: "Средний",
      title: "Поставить цель по сокращению выбросов",
      why: "У компании нет утверждённой цели по выбросам. Банки и международные покупатели всё чаще её спрашивают; без цели нельзя оценить прогресс.",
      actions: [
        "Принять базовый год — этот отчётный период — и зафиксировать выбросы Охватов 1+2",
        "Утвердить цель приказом руководителя и включить её в бюджет мероприятий",
        "Пересчитывать выбросы каждый квартал в FinLite и сравнивать с траекторией",
      ],
      effect: `Ориентир: −4,2% в год (линейная траектория, совместимая с удержанием потепления в пределах 1,5 °C). При годовых выбросах около ${t(annual, 1)} это ${t(annual * 0.042, 2)} в год, или −12,6% к ${periodYear + 3} году.`,
      kpi: "т CO₂-экв. Охватов 1+2 к базовому году, %",
      horizon: "решение — в ближайший квартал", gri: "305-5, IFRS S2 п. 33",
    });
  }
  if (r.waste.total > 0 && (r.waste.recycledShare ?? 0) < 30) {
    out.push({
      pillar: "E", priority: "Низкий",
      title: "Раздельный сбор и переработка отходов",
      why: `На переработку передаётся ${pct(r.waste.recycledShare ?? 0)} отходов.`,
      actions: ["Поставить контейнеры для бумаги, пластика и металла", "Заключить договор с переработчиком (макулатура, пластик, металлолом, электроника)", "Вести журнал учёта отходов по видам"],
      effect: `Доведение доли переработки до 50% — ещё ${num(Math.max(0, r.waste.total * 0.5 - r.waste.recycled), 2)} т отходов вместо полигона.`,
      kpi: "доля отходов на переработку, %",
      horizon: "до 6 месяцев", gri: "306-2, 306-4",
    });
  }
  if (!(input.waterM3 > 0) || !(input.wasteT > 0)) {
    out.push({
      pillar: "E", priority: "Низкий",
      title: "Наладить учёт воды и отходов",
      why: `Нет данных: ${[!(input.waterM3 > 0) ? "водопотребление" : "", !(input.wasteT > 0) ? "отходы" : ""].filter(Boolean).join(" и ")}. Эти показатели входят в обязательное раскрытие по GRI 303 и 306.`,
      actions: ["Снимать показания водомеров ежемесячно", "Сохранять акты вывоза отходов с указанием массы"],
      effect: "Полное раскрытие экологических показателей в следующем отчёте.",
      kpi: "доля заполненных экологических показателей",
      horizon: "следующий отчётный период", gri: "303-5, 306-3",
    });
  }

  // ── S ──
  if (r.workforce.turnover !== null && r.workforce.turnover * yearFactor > 20) {
    out.push({
      pillar: "S", priority: "Высокий",
      title: "Снизить текучесть кадров",
      why: `Текучесть за период — ${pct(r.workforce.turnover)} (около ${pct(r.workforce.turnover * yearFactor, 0)} в пересчёте на год). Замена сотрудника обычно обходится в несколько месячных окладов.`,
      actions: ["Проводить выходные интервью и разбирать причины увольнений", "Пересмотреть оплату на позициях с наибольшей текучестью", "Ввести наставничество для новых сотрудников на первые 3 месяца"],
      effect: r.pay.avgWage ? `Каждый удержанный сотрудник экономит затраты на поиск и обучение — ориентировочно 1–3 средние зарплаты (${som(r.pay.avgWage)}–${som(r.pay.avgWage * 3)}).` : "Снижение затрат на найм и обучение.",
      kpi: "текучесть, % в год",
      horizon: "6–12 месяцев", gri: "401-1",
    });
  }
  if (input.employees > 0) {
    const annualHours = (r.training.perEmployee ?? 0) * yearFactor;
    if (annualHours < 16) {
      out.push({
        pillar: "S", priority: "Средний",
        title: "План обучения персонала",
        why: `На сотрудника приходится ${num(r.training.perEmployee ?? 0)} ч обучения за период (около ${num(annualHours, 0)} ч в год)${r.training.spend > 0 ? `, расходы на обучение — ${som(r.training.spend)}` : ", расходов на обучение по счёту 8160 нет"}.`,
        actions: ["Составить годовой план обучения по должностям", "Включить обязательные темы: охрана труда, антикоррупция, защита данных", "Учитывать часы обучения в кадровом учёте"],
        effect: "Ориентир — не менее 16 часов обучения на сотрудника в год.",
        kpi: "часы обучения на сотрудника; доля обученных, %",
        horizon: "12 месяцев", gri: "404-1, 404-2",
      });
    }
  }
  if (r.pay.toNational !== null && r.pay.toNational < 100) {
    out.push({
      pillar: "S", priority: "Средний",
      title: "Пересмотреть уровень оплаты труда",
      why: `Средняя зарплата в компании — ${pct(r.pay.toNational)} от средней по стране.`,
      actions: ["Сравнить зарплаты по должностям с рынком", "Определить позиции ниже рынка и график повышения", "Связать премии с результатами"],
      effect: "Снижение текучести и затрат на найм, рост производительности.",
      kpi: "средняя зарплата к средней по КР, %",
      horizon: "12 месяцев", gri: "202-1",
    });
  }
  if (r.workforce.womenManagersShare !== null && r.workforce.womenManagersShare < 30 && input.managers >= 2) {
    out.push({
      pillar: "S", priority: "Низкий",
      title: "Равные возможности для карьерного роста",
      why: `Женщины составляют ${pct(r.workforce.womenShare ?? 0)} персонала, но ${pct(r.workforce.womenManagersShare)} руководителей.`,
      actions: ["Включать женщин в кадровый резерв на руководящие должности", "Проверить, нет ли разрыва в оплате на равных позициях"],
      effect: "Более широкий кадровый резерв, соответствие ожиданиям международных партнёров.",
      kpi: "доля женщин среди руководителей, %",
      horizon: "1–3 года", gri: "405-1, 405-2",
    });
  }
  if (input.injuries > 0 || r.safety.hoursEstimated) {
    out.push({
      pillar: "S", priority: input.injuries > 0 ? "Высокий" : "Низкий",
      title: input.injuries > 0 ? "Охрана труда: разбор несчастных случаев" : "Учёт отработанного времени для охраны труда",
      why: input.injuries > 0
        ? `За период — ${num(input.injuries, 0)} несчастных случая с потерей трудоспособности, коэффициент травматизма ${num(r.safety.ltifr ?? 0, 2)} на 1 млн чел.-ч.`
        : "Отработанные человеко-часы не указаны — коэффициент травматизма посчитан по оценке.",
      actions: input.injuries > 0
        ? ["Расследовать каждый случай и устранить причину", "Провести внеплановый инструктаж и проверку СИЗ", "Оценить условия труда на рабочих местах"]
        : ["Брать человеко-часы из табеля учёта рабочего времени"],
      effect: input.injuries > 0 ? "Цель — ноль несчастных случаев." : "Точный коэффициент травматизма в следующем отчёте.",
      kpi: "LTIFR; дни нетрудоспособности",
      horizon: input.injuries > 0 ? "немедленно" : "следующий период", gri: "403-9",
    });
  }

  // ── G ──
  const missing = r.governance.policies.filter((p) => !p.adopted);
  if (missing.length) {
    const dataFirst = (input.industry === "it" || input.industry === "services") && missing.some((p) => p.key === "dataProtectionPolicy");
    out.push({
      pillar: "G", priority: missing.length >= 3 || dataFirst ? "Высокий" : "Средний",
      title: "Утвердить недостающие политики",
      why: `Не утверждены: ${missing.map((p) => p.label.toLowerCase()).join("; ")}.`,
      actions: ["Утвердить политики приказом руководителя или решением участников", "Ознакомить сотрудников под подпись и включить в вводное обучение", "Назначить ответственного за соблюдение и канал для сообщений о нарушениях"],
      effect: "Снижение юридических и репутационных рисков; закрытие раскрытий GRI 2-23 и 205-2.",
      kpi: "число утверждённых политик; доля ознакомленных сотрудников",
      horizon: "3 месяца", gri: "2-23, 2-24, 205-2",
    });
  }
  if (input.boardMembers > 0 && !(input.independentBoard > 0)) {
    out.push({
      pillar: "G", priority: "Низкий",
      title: "Независимый взгляд в управлении",
      why: "В органе управления нет независимых членов.",
      actions: ["Пригласить независимого члена совета или внешнего советника", "Раз в год проводить внешний аудит отчётности"],
      effect: "Повышение доверия банков и инвесторов.",
      kpi: "доля независимых членов, %",
      horizon: "1–2 года", gri: "2-9",
    });
  }
  if (r.tax.finesBudget > 0) {
    out.push({
      pillar: "G", priority: "Высокий",
      title: "Налоговая дисциплина",
      why: `За период начислены штрафы и пени в бюджет — ${som(r.tax.finesBudget)}.`,
      actions: ["Вести налоговый календарь с напоминаниями", "Начислять налоги в FinLite в конце каждого периода и сверять с декларациями"],
      effect: `Прямая экономия ${som(r.tax.finesBudget)} за аналогичный период.`,
      kpi: "штрафы и пени, сом",
      horizon: "немедленно", gri: "2-27, 207-2",
    });
  }
  if (s.checks.some((c) => c.id === "tax" && c.status !== "ok")) {
    out.push({
      pillar: "G", priority: "Высокий",
      title: "Начислить налоги за период",
      why: "Сверка «Налоги начислены по режиму» не пройдена — налоговые показатели отчёта могут быть занижены.",
      actions: ["Открыть «Отчётность» → «Налоги» и начислить налоги за период"],
      effect: "Корректные налоговые раскрытия GRI 207.",
      kpi: "сверка «Налоги начислены» пройдена",
      horizon: "до сдачи отчёта", gri: "207-4",
    });
  }
  if (!input.esgOwner.trim()) {
    out.push({
      pillar: "G", priority: "Средний",
      title: "Назначить ответственного за ESG",
      why: "Ответственный за устойчивое развитие не указан.",
      actions: ["Закрепить функцию за руководителем (финансовый директор, заместитель)", "Утвердить график сбора нефинансовых данных"],
      effect: "Регулярная отчётность без авралов.",
      kpi: "наличие ответственного; отчёт в срок",
      horizon: "1 месяц", gri: "2-13",
    });
  }
  if (r.gaps.length >= 3) {
    out.push({
      pillar: "G", priority: "Средний",
      title: "Система сбора нефинансовых данных",
      why: `Не хватает данных по ${r.gaps.length} показателям — часть раскрытий частичная.`,
      actions: ["Закрепить источник каждого показателя (счётчики, табель, акты)", "Вносить данные в FinLite ежеквартально"],
      effect: "Полное раскрытие и сравнимость с прошлыми периодами.",
      kpi: `заполнено ${r.completeness.filled} из ${r.completeness.total} ключевых показателей`,
      horizon: "следующий период", gri: "2-4",
    });
  }

  return out.sort((a, b) => ORDER[a.priority] - ORDER[b.priority]);
}
