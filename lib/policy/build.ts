/** Accounts used in the journal + the usual ones for the chosen activities. */
export function workingChart(p: PolicyInput, entries: LedgerEntry[]): Array<{ code: string; name: string; used: boolean }> {
  const used = new Set<string>();
  for (const e of entries) for (const l of e.lines) used.add(l.account);
  const wanted = new Set<string>([...BASE_ACCOUNTS, ...p.activities.flatMap((a) => BY_ACTIVITY[a] ?? []), ...used]);
  if (p.vatPayer) { wanted.add("3430"); }
  return ACCOUNTS
    .filter((a) => !a.header && wanted.has(a.code))
    .map((a) => ({ code: a.code, name: a.name, used: used.has(a.code) }));
}

